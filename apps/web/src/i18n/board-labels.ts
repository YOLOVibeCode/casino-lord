export function formatBoardLabel(key: string, language: BoardLanguage): string {
  const entry = LABELS[key];
  if (!entry) return key;

  switch (language) {
    case "EN":
      return entry.en;
    case "ZH":
      return entry.zh;
    case "EN+ZH":
      return `${entry.en} / ${entry.zh}`;
  }
}
